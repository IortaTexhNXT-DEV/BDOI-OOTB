def _scene_users():
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, os.path.join(here, '..', '..', 'manual', 'tools'))
    try:
        import scenes
    except Exception:
        return {}
    out = {}
    for sc in getattr(scenes, 'SCENES', []) + getattr(scenes, 'LATE_SCENES', []):
        for st in sc['steps']:
            if st[0] == 'shot':
                out[st[1]] = sc['user']
    return out


SCENE_USER = _scene_users()


def shot(name, screen, crop=None):
    """A user manual screenshot with a caption that names the screen and the user it was captured as."""
    user = SCENE_USER.get(name)
    who = ROLE_OF.get(user, user)
    caption = (f'Live screen: {screen}. Signed in as {who}.' if who
               else f'Sign-in page: {screen} (example values, nothing sent to the server).')
    d = dict(shot='manual:' + name, caption=caption)
    if crop:
        d['crop'] = crop
    return d


