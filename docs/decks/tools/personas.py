def reports_for(role):
    """Codes of the reports a role may run, in catalogue group order."""
    order = [c for _, cs in REPORT_GROUPS for c in cs]
    if role == 'system-admin':
        return order
    return [c for c in order if role in REPORTS[c][3]]


