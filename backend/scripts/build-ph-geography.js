#!/usr/bin/env node
/**
 * Build the Philippine geography reference seed (src/db/seeds/12_ph_geography.sql) from the PSGC files in
 * src/db/reference/psgc: regions, provinces (plus Metro Manila and the BARMM Special Geographic Area), cities and
 * municipalities with their PSGC code, class and ZIP code, the PhilPost ZIP code list, and the barangays of Metro Manila.
 * The barangays of the other regions are an optional load (scripts/load-barangays.js).
 *
 *   node scripts/build-ph-geography.js
 *
 * Run it again after replacing the CSV files with a newer PSGC release (src/db/reference/psgc/VERSION names the
 * release; docs/onboarding/GO_LIVE_DATA_SETUP.md gives the procedure). The seed is idempotent: it adds what is missing,
 * attaches the PSGC code to provinces and cities entered before (matched by name), and never overwrites a record an
 * administrator changed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PSGC_DIR, psgcVersion, readPsgc } from './lib/psgc.js';

const backend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SEED_FILE = path.join(backend, 'src', 'db', 'seeds', '12_ph_geography.sql');

const lit = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const values = (rows, cols) => rows.map((r) => `(${cols.map((c) => (typeof c === 'function' ? c(r) : lit(r[c]))).join(',')})`).join(',\n');

export function buildSql(dir = PSGC_DIR) {
  const version = psgcVersion(dir);
  const regions = readPsgc('regions.csv', dir);
  const provinces = readPsgc('provinces.csv', dir);
  const cities = readPsgc('cities.csv', dir);
  const postal = readPsgc('postal_codes.csv', dir);
  const ncrBarangays = readPsgc('barangays.csv', dir).filter((b) => b.city_psgc.startsWith('13'));
  const PH = "(SELECT id FROM countries WHERE code = 'PH')";
  return `-- Philippine geography: GENERATED by scripts/build-ph-geography.js from src/db/reference/psgc (do not edit by hand).
-- ${version}
-- ${regions.length} regions, ${provinces.filter((p) => p.level === 'Province').length} provinces (plus Metro Manila and the BARMM Special Geographic Area),
-- ${cities.length} cities and municipalities, ${postal.length} PhilPost ZIP codes, ${ncrBarangays.length} Metro Manila barangays.
-- Idempotent: adds what is missing; provinces and cities entered before are matched by name and get their PSGC code
-- (their names and codes are kept); records an administrator changed are not overwritten.

-- ---------- regions ----------
INSERT INTO regions(country_id, code, name, designation, psgc_code, sort_order, attrs, created_by)
SELECT ${PH}, v.code, v.name, v.designation, v.psgc, v.sort, jsonb_build_object('Description', v.name), 'seed'
FROM (VALUES
${values(regions.map((r, i) => ({ ...r, sort: i + 1 })), ['code', 'name', 'designation', 'psgc_code', (r) => String(r.sort)])}
) AS v(code, name, designation, psgc, sort)
WHERE ${PH} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM regions r WHERE r.psgc_code = v.psgc OR (r.country_id = ${PH} AND lower(r.code) = lower(v.code)));

-- ---------- provinces (Metro Manila and the Special Geographic Area are province-level areas without a province) ----------
CREATE TEMP TABLE psgc_province(psgc text, code text, name text, region_psgc text, level text) ON COMMIT DROP;
INSERT INTO psgc_province VALUES
${values(provinces, ['psgc_code', 'code', 'name', 'region_psgc', 'level'])};
-- provinces entered before the PSGC list (matched by name, once): PSGC code, region, ISO 3166-2:PH code
UPDATE states s SET psgc_code = COALESCE(s.psgc_code, v.psgc), region_id = COALESCE(s.region_id, r.id),
  code = CASE WHEN s.psgc_code IS NULL THEN v.code ELSE s.code END,
  attrs = jsonb_build_object('Level', v.level) || s.attrs, updated_by = COALESCE(s.updated_by, 'seed')
FROM psgc_province v JOIN regions r ON r.psgc_code = v.region_psgc
WHERE s.country_id = ${PH} AND NOT s.attrs ? 'Level' AND (s.psgc_code = v.psgc OR (s.psgc_code IS NULL AND lower(s.name) = lower(v.name)));
INSERT INTO states(country_id, code, name, region_id, psgc_code, attrs, created_by)
SELECT ${PH}, v.code, v.name, r.id, v.psgc, jsonb_build_object('Description', v.name, 'Level', v.level), 'seed'
FROM psgc_province v JOIN regions r ON r.psgc_code = v.region_psgc
WHERE NOT EXISTS (SELECT 1 FROM states s WHERE s.country_id = ${PH} AND (s.psgc_code = v.psgc OR lower(s.name) = lower(v.name)));

-- ---------- cities and municipalities ----------
CREATE TEMP TABLE psgc_city(psgc text, name text, official text, class text, province_psgc text, region_psgc text, ncr_district text, zip text) ON COMMIT DROP;
INSERT INTO psgc_city VALUES
${values(cities, ['psgc_code', 'name', 'official_name', 'city_class', 'province_psgc', 'region_psgc', 'ncr_district', 'zip_code'])};
CREATE TEMP TABLE psgc_city_parent ON COMMIT DROP AS
SELECT v.*, s.id AS state_id, r.id AS region_id FROM psgc_city v
JOIN states s ON s.country_id = ${PH} AND (s.psgc_code = v.province_psgc OR (v.province_psgc = 'NCR' AND s.code = 'NCR' AND s.attrs->>'Level' = 'Metropolitan area'))
JOIN regions r ON r.psgc_code = v.region_psgc;
-- cities entered before the PSGC list, matched once by name inside their province ("Makati" = "City of Makati")
UPDATE cities ci SET psgc_code = v.psgc, region_id = v.region_id, city_class = COALESCE(ci.city_class, v.class), zip_code = COALESCE(ci.zip_code, v.zip),
  attrs = jsonb_strip_nulls(jsonb_build_object('OfficialName', v.official, 'NcrDistrict', NULLIF(v.ncr_district, ''))) || ci.attrs
FROM psgc_city_parent v
WHERE ci.psgc_code IS NULL AND ci.state_id = v.state_id AND ph_place_key(ci.name) = ph_place_key(v.name)
  AND NOT EXISTS (SELECT 1 FROM cities x WHERE x.psgc_code = v.psgc);
INSERT INTO cities(state_id, region_id, name, psgc_code, city_class, zip_code, attrs, created_by)
SELECT v.state_id, v.region_id, v.name, v.psgc, v.class, NULLIF(v.zip, ''),
  jsonb_strip_nulls(jsonb_build_object('CityCode', v.psgc, 'Description', v.official, 'OfficialName', v.official, 'NcrDistrict', NULLIF(v.ncr_district, ''))), 'seed'
FROM psgc_city_parent v
WHERE NOT EXISTS (SELECT 1 FROM cities ci WHERE ci.psgc_code = v.psgc);

-- ---------- PhilPost ZIP codes (look-up used to fill an address from its ZIP code) ----------
INSERT INTO postal_codes(country_code, code, province, city, district)
SELECT 'PH', v.zip, s.name, ci.name, v.place FROM (VALUES
${values(postal, ['zip_code', 'place', 'city_psgc'])}
) AS v(zip, place, city) JOIN cities ci ON ci.psgc_code = v.city JOIN states s ON s.id = ci.state_id
ON CONFLICT (country_code, code, district) DO NOTHING;

-- ---------- barangays of Metro Manila (the other regions: scripts/load-barangays.js) ----------
INSERT INTO districts(city_id, name, psgc_code, created_by)
SELECT ci.id, v.name, v.psgc, 'seed' FROM (VALUES
${values(ncrBarangays, ['psgc_code', 'name', 'city_psgc'])}
) AS v(psgc, name, city) JOIN cities ci ON ci.psgc_code = v.city
WHERE NOT EXISTS (SELECT 1 FROM districts d WHERE d.psgc_code = v.psgc)
ON CONFLICT (city_id, name) DO UPDATE SET psgc_code = COALESCE(districts.psgc_code, EXCLUDED.psgc_code);

-- ZIP code of the PhilPost list that names the barangay
UPDATE districts d SET postal_code = p.code FROM cities ci JOIN states s ON s.id = ci.state_id
JOIN postal_codes p ON upper(p.country_code) = 'PH' AND lower(p.city) = lower(ci.name) AND lower(p.province) = lower(s.name)
WHERE d.city_id = ci.id AND ci.psgc_code LIKE '13%' AND d.postal_code IS NULL AND ph_place_key(p.district) = ph_place_key(d.name);

-- release of the geographic codes, shown with the country
UPDATE countries SET attrs = attrs || jsonb_build_object('PsgcRelease', ${lit(version)}) WHERE code = 'PH';

-- ---------- LGU tax rates: link the rates entered by name to their city / municipality ----------
UPDATE lgu_tax_rates l SET city_id = (
  SELECT ci.id FROM cities ci JOIN states s ON s.id = ci.state_id
  WHERE s.country_id = ${PH} AND ci.status = 'active' AND ph_place_key(ci.name) = ph_place_key(l.name)
    AND (l.province IS NULL OR lower(s.name) = lower(l.province)) ORDER BY ci.psgc_code NULLS LAST, ci.id LIMIT 1)
WHERE l.city_id IS NULL;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(SEED_FILE, buildSql());
  console.log(`Wrote ${path.relative(process.cwd(), SEED_FILE)}`);
}
