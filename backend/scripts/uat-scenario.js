/**
 * UAT data scenario: runs the complete broking cycle of a Philippine non-life broker through the public HTTP API
 * (personas, masters, sales, placement, billing, servicing, money, reconciliation, month-end, reports), with
 * synthetic data spread over the last six months. It can be pointed at any environment.
 *
 *   API_BASE=http://127.0.0.1:8000/api ADMIN_PASSWORD=... PERSONA_PASSWORD=... node scripts/uat-scenario.js
 *
 * Environment:
 *   API_BASE          API root, e.g. http://127.0.0.1:8201/api or http://api.railway.internal:8000/api
 *   ADMIN_USER        the built-in administrator (default BrokerVerse)
 *   ADMIN_PASSWORD    its password
 *   PERSONA_PASSWORD  password given to the persona users the scenario creates (must meet the password policy)
 *   UAT_SEED          random seed (default brokerverse-uat): the same seed gives the same data
 *   UAT_SCALE         volume multiplier (default 1: about 40 retail and 20 corporate clients)
 *   UAT_MONTHS        months of history (default 6, the current month included)
 *   UAT_REPORT        run log file (default docs/e2e/UAT_SCENARIO_RUN.md of the repository; "none" to skip)
 *
 * Load it once, on a database without business records: when policies already exist the business steps are skipped
 * and only the reports and dashboards are checked (masters and personas are looked up before they are created). Exit code 1 when a step failed.
 */
import fs from 'node:fs';
import { loadConfig } from './uat/config.js';
import { Api } from './uat/http.js';
import { RunLog } from './uat/log.js';
import { Random } from './uat/random.js';
import { setup } from './uat/phases/setup.js';
import { findMarker, startMarker, finishMarker } from './uat/phases/marker.js';
import { runBusiness } from './uat/phases/business.js';
import { reports } from './uat/phases/reports.js';

const cfg = loadConfig();
const log = new RunLog({ quiet: cfg.quiet });
log.hide(cfg.adminPassword, cfg.personaPassword);

const ctx = {
  cfg, log, api: new Api(cfg.apiBase), rnd: new Random(cfg.seed),
  as: {}, insurers: {}, products: {}, bankAccounts: {}, clients: [], policies: [], state: {},
};

async function main() {
  log.info(`UAT scenario against ${cfg.apiBase} (seed ${cfg.seed}, scale ${cfg.scale})`);
  await setup(ctx);
  const marker = await findMarker(ctx);
  if (marker?.state === 'complete') {
    log.note(`The UAT data was already loaded on ${marker.completedAt} (seed ${marker.seed}); business steps skipped, reports checked again.`);
  } else {
    if (marker) log.note('An earlier run did not finish (marker in progress); its records are kept and this run adds a new batch.');
    await startMarker(ctx, marker);
    await runBusiness(ctx);
    await finishMarker(ctx);
  }
  await reports(ctx);
}

let crashed = null;
try {
  await main();
} catch (e) {
  crashed = e;
  log.info(`stopped: ${e.message}`);
}
const context = [
  ['API', cfg.apiBase], ['Seed', cfg.seed], ['Scale', cfg.scale], ['Business date', ctx.today || ''],
  ['Months', (ctx.months || []).map((m) => m.period).join(', ')], ['API calls', ctx.api.calls],
  ['Result', crashed ? `stopped: ${crashed.message}` : log.failures.length ? `${log.failures.length} step(s) failed` : 'all steps passed'],
];
log.print('');
for (const l of log.summaryLines()) log.print(l);
for (const [k, v] of [...log.counts.entries()]) log.print(`  ${k}: ${v}`);
log.print(`${log.steps.length} steps, ${log.failures.length} failed${crashed ? ' (stopped early)' : ''}`);
if (cfg.report) {
  // hand-written sections of the report (from "## Defects found and fixed" on) are kept across runs
  const kept = fs.existsSync(cfg.report) ? fs.readFileSync(cfg.report, 'utf8').split(/\n(?=## Defects found and fixed)/)[1] : null;
  const intro = 'Generated by `backend/scripts/uat-scenario.js`. The scenario drives the public API only, with one persona per role; '
    + 'a failed step shows the API call and the answer it got.';
  log.write(cfg.report, { title: 'UAT scenario run', intro, context, sections: ctx.reportSections || [] });
  if (kept) fs.appendFileSync(cfg.report, `\n${kept.trimEnd()}\n`);
  log.print(`run log written to ${cfg.report}`);
}
process.exit(crashed || log.failures.length ? 1 : 0);
